    fun get(gospel: Gospel, chapter: Int): String {
        val arr = when (gospel) {
            Gospel.MATTHEW -> matthew
            Gospel.MARK    -> mark
            Gospel.LUKE    -> luke
            Gospel.JOHN    -> john
        }
        val idx = chapter - 1
        return if (idx in arr.indices) arr[idx] else ""
    }
